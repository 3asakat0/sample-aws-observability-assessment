export type ReportLanguage = 'en' | 'ja';
export type MessageKey = keyof typeof en;
export type Translator = (key: MessageKey, values?: Record<string, string | number>) => string;

export function reportLanguage(value: unknown): ReportLanguage {
  return value === 'ja' ? 'ja' : 'en';
}

export function createTranslator(language: unknown): Translator {
  const messages: Messages = reportLanguage(language) === 'ja' ? ja : en;
  return (key, values) => values
    ? messages[key].replace(/\{(\w+)\}/g, (placeholder, name: string) => String(values[name] ?? placeholder))
    : messages[key];
}

export const ReportLanguageContext = createContext<ReportLanguage>('en');

export function useReportTranslation(): Translator {
  const language = useContext(ReportLanguageContext);
  return useMemo(() => createTranslator(language), [language]);
}
